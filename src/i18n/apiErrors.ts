/** Traduz uma mensagem de erro do site para o idioma atual; sem tradução, devolve como veio. */
export function translateApiText(msg: string): string {
  if (getCurrentLang() !== "en") return msg;
  return API_ERRORS_EN[msg] ?? en[msg] ?? msg;
}
